const $ = (id) => document.getElementById(id);

function parseEmbedded(id){
  try{ return JSON.parse($(id).textContent); }catch(_){ return null; }
}
const bundle = parseEmbedded('bundleData');
const live = parseEmbedded('liveIdentity') || {};
const UNRESOLVED = (bundle && bundle.unresolved_signals) || [];

/* Every dynamic value on this page goes through textContent. The bundle is
   generated by our own scripts, but a page that renders "trusted" data as
   markup is one committed fixture away from being wrong about that. */
function text(id, value){ $(id).textContent = value === null || value === undefined ? '—' : String(value); }

function row(cells, tag){
  const tr = document.createElement('tr');
  cells.forEach(value => {
    const cell = document.createElement(tag || 'td');
    cell.textContent = value === null || value === undefined ? '—' : String(value);
    tr.appendChild(cell);
  });
  return tr;
}

function table(head, rows, minWidth){
  const wrap = document.createElement('div');
  wrap.className = 'table-wrap';
  wrap.tabIndex = 0;                       // reachable, and scrollable, by keyboard
  wrap.setAttribute('role', 'region');
  const el = document.createElement('table');
  if (minWidth) el.style.minWidth = minWidth;
  const thead = document.createElement('thead');
  thead.appendChild(row(head, 'th'));
  el.appendChild(thead);
  const tbody = document.createElement('tbody');
  rows.forEach(r => tbody.appendChild(row(r)));
  el.appendChild(tbody);
  wrap.appendChild(el);
  return wrap;
}

// --- provenance and staleness ----------------------------------------------
//
// A committed recording is stale the moment the policy or the code moves. The
// page cannot re-run anything to find out, so it compares identities and says
// what it sees. Silence here would be the page asserting freshness it has no
// evidence for.
function renderProvenance(){
  if (!bundle){
    $('emptyBanner').hidden = false;
    ['limitsCard','caseCard','comparisonCard','evidenceCard'].forEach(id => { $(id).hidden = true; });
    return false;
  }
  const drift = [];
  if (live.policy_digest && live.policy_digest !== bundle.policy_digest){
    drift.push('the policy file has changed since these runs were recorded');
  }
  if (live.code_revision && live.code_revision !== 'unknown' && bundle.code_revision !== 'unknown'
      && live.code_revision !== bundle.code_revision){
    drift.push('the code has moved to a different revision');
  }
  if (drift.length){
    $('staleBanner').hidden = false;
    $('staleBanner').textContent =
      'These recordings may no longer match what is running: ' + drift.join(', ')
      + '. Regenerate them with scripts/build_lab_artifacts.py before drawing a conclusion.';
  }
  if (bundle.dirty || live.dirty){
    $('dirtyBanner').hidden = false;
    $('dirtyBanner').textContent = live.code_revision === 'unknown' || bundle.code_revision === 'unknown'
      ? 'The runtime source identity could not be verified. These recordings cannot be confirmed against the running code.'
      : bundle.dirty
      ? 'Recorded from a working tree with uncommitted changes, so the recorded code revision does not fully identify what ran. It is reproducible only against that same tree.'
      : 'The running tree has uncommitted changes, so its revision does not fully identify what is running now.';
  }
  $('provenanceFoot').textContent =
    'Bundle schema ' + bundle.schema_version + ' · recorded ' + bundle.generated_at
    + ' · policy ' + bundle.policy_digest + ' · revision ' + bundle.code_revision
    + '. Authored synthetic fixtures throughout; nothing on this page is signed, '
    + 'and nothing on it is a merchant decision.';

  const limits = $('limits');
  limits.replaceChildren();
  (bundle.limits || []).forEach(line => {
    const li = document.createElement('li');
    li.textContent = line;
    limits.appendChild(li);
  });
  return true;
}

// --- case selection and replay ---------------------------------------------

let order = [];
let selected = null;
const modelRuns = new Map();
const modelViews = new Set();
let modelBusy = false;
let playTimer = null;
let shown = 0;      // how many recorded events are revealed

const caseById = (id) => {
  const entry = (bundle.cases || []).find(c => c.case_id === id);
  return entry && modelViews.has(id) && modelRuns.has(id) ? {...entry, run:modelRuns.get(id)} : entry;
};

function renderCaseButtons(){
  const holder = $('cases');
  holder.replaceChildren();
  order.forEach(id => {
    const entry = caseById(id);
    if (!entry) return;                     // an id with no recording selects nothing
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'case-btn';
    const name = document.createElement('strong');
    name.textContent = caseName(entry);
    const description = document.createElement('span');
    description.className = 'case-description';
    description.textContent = entry.description;
    const outcome = document.createElement('span');
    outcome.className = 'case-outcome ' + entry.run.outcome.decision;
    outcome.textContent = entry.run.outcome.decision + ' · ' + entry.run.outcome.evidence_steps + ' checks';
    button.append(name, description, outcome);
    button.setAttribute('aria-pressed', String(id === selected));
    button.addEventListener('click', () => selectCase(id));
    holder.appendChild(button);
  });
}

function assumptionsFor(entry){
  const parts = [entry.description];
  if (entry.fault_profile){
    parts.push('The provider is wrapped in a lab-only fault profile ('
      + entry.fault_profile + '). This simulates a network that does not answer; it is '
      + 'not a real outage and not an OAuth expiry.');
  }
  if (entry.removes_claimed_location){
    parts.push('The customer never claimed a location in this case, so the location '
      + 'check has nothing to compare against. An input that is absent stays '
      + 'unresolved; it never becomes a positive fact.');
  }
  parts.push('Base scenario fixture: ' + entry.scenario_id + '. Authored, not independent ground truth.');
  return parts;
}

function selectCase(id){
  pauseReplay();
  const entry = caseById(id);
  if (!entry) return;
  selected = id;
  text('caseTitle', caseName(entry));
  updateModelStatus();
  renderCaseButtons();
  $('caseDetail').hidden = false;

  const assumptions = $('assumptions');
  assumptions.replaceChildren();
  const heading = document.createElement('b');
  heading.textContent = 'Before you look at the result: ';
  assumptions.appendChild(heading);
  assumptionsFor(entry).forEach((line, index) => {
    const p = document.createElement('div');
    p.textContent = line;
    if (index) p.style.marginTop = '5px';
    assumptions.appendChild(p);
  });

  const run = entry.run;
  const total = (run.events || []).length;
  const scrub = $('scrub');
  scrub.max = String(Math.max(total, 1));
  scrub.value = String(total);
  shown = total;
  renderEvents();

  text('outDecision', run.outcome && run.outcome.decision);
  $('outDecision').className = 'decision ' + ((run.outcome && run.outcome.decision) || '');
  text('outGrade', run.outcome && run.outcome.chain_grade);
  text('outConfidence', run.outcome && run.outcome.confidence);
  text('outSteps', run.outcome && run.outcome.evidence_steps);
  text('outCost', run.outcome && run.outcome.evidence_cost);

  $('runPlanner').replaceChildren(plannerTag(run.planner_source));
  text('runFixture', run.fixture_digest);
  text('runPolicy', run.policy_digest);
  text('runCode', run.dirty ? run.code_revision + ' (dirty)' : run.code_revision);
  text('runWhen', run.generated_at);
  text('runTiming', run.timing_basis === 'stage_pacing'
    ? 'ordering only — no durations were measured'
    : run.timing_basis);
}

/* The selection's real source, from the recorded event, never a label chosen
   because of how the run was configured. A heuristic described as reasoning is
   a worse problem than a heuristic. */
function plannerTag(source){
  const tag = document.createElement('span');
  tag.className = 'tag ' + (source || '');
  tag.textContent = source || 'unrecorded';
  return tag;
}

const DIAGNOSTICS = {
  no_key: 'no model credential was configured, so the deterministic planner chose',
  timeout: 'the model did not answer in time, so the deterministic planner chose',
  malformed: 'the model returned something unusable, so the deterministic planner chose',
  invalid_action: 'the model asked for an action outside the allowed set',
  call_cap: 'the per-run model call cap was reached',
  provider_error: 'the provider call failed'
};

function renderEvents(){
  const entry = caseById(selected);
  const list = $('events');
  list.replaceChildren();
  if (!entry) return;
  const events = entry.run.events || [];
  events.forEach(event => {
    const li = document.createElement('li');
    li.className = 'event' + (event.sequence > shown ? ' pending' : '');
    const head = document.createElement('div');
    head.className = 'event-head';
    const title = document.createElement('span');
    title.className = 'event-title';
    const name = event.action || event.api || event.phase || event.event_type;
    title.textContent = event.sequence + '. ' + name;
    head.appendChild(title);
    const meta = document.createElement('span');
    meta.className = 'event-meta';
    // Budget movement, as recorded — absent rather than computed when the
    // event did not carry it. The event type is only repeated when it is not
    // already the row's own name.
    const bits = [];
    if (event.event_type !== name) bits.push(event.event_type);
    if (event.budget_before !== null && event.budget_after !== null){
      bits.push('budget ' + event.budget_before + ' → ' + event.budget_after);
    }
    if (event.belief_after !== null && event.belief_after !== undefined){
      bits.push('belief ' + event.belief_after);
    }
    meta.textContent = bits.join(' · ');
    head.appendChild(meta);
    li.appendChild(head);

    // What the network answered, so an evidence row can be reconciled rather
    // than merely counted. `max_age_hours` is the window the question covered,
    // never the age of an event: CAMARA answers with a boolean and no
    // timestamp, so an event age would be invented.
    if (event.signal || event.result){
      const answer = document.createElement('div');
      answer.className = 'event-detail';
      const parts = [];
      if (event.signal) parts.push(event.signal);
      if (event.result) parts.push(event.result);
      if (event.max_age_hours !== null && event.max_age_hours !== undefined){
        parts.push('asked over the last ' + event.max_age_hours + 'h');
      }
      answer.textContent = parts.join(' · ');
      // Classified with the investigator's own set, shipped in the bundle. A
      // second copy of it here would drift, and "the network did not answer"
      // versus "the network reported a mismatch" is exactly the distinction
      // this page must not blur (I4 step 3).
      if (UNRESOLVED.includes(event.signal)){
        answer.classList.add('diag');
        answer.textContent += ' — the network did not answer. That is a hole in the chain, not a finding: it is not a mismatch, and it never becomes a pass.';
      }
      li.appendChild(answer);
    }

    if (event.selection_source){
      const detail = document.createElement('div');
      detail.className = 'event-detail';
      detail.appendChild(plannerTag(event.selection_source));
      // Only the rationale that was actually returned. A rationale that was
      // never captured says so; it is not written afterwards.
      const said = document.createElement('span');
      said.textContent = event.rationale || 'no rationale was captured for this selection';
      if (!event.rationale) said.style.opacity = '.7';
      detail.appendChild(said);
      li.appendChild(detail);
    }
    if (event.diagnostic){
      const diag = document.createElement('div');
      diag.className = 'event-detail diag';
      diag.textContent = DIAGNOSTICS[event.diagnostic] || event.diagnostic;
      li.appendChild(diag);
    }
    if (event.evidence_step_ref !== null && event.evidence_step_ref !== undefined){
      const ref = document.createElement('div');
      ref.className = 'event-detail';
      ref.textContent = 'evidence link #' + event.evidence_step_ref;
      li.appendChild(ref);
    }
    list.appendChild(li);
  });
  $('scrubCount').textContent = shown + ' / ' + events.length;
  $('stepBackBtn').disabled = shown <= 0;
  $('stepFwdBtn').disabled = shown >= events.length;
  renderRisk(events);
  const active = list.children[Math.max(shown - 1, 0)];
  if (active && playTimer) list.scrollTop = Math.max(0, active.offsetTop - list.offsetTop - list.clientHeight / 2);
}

function setShown(value){
  const entry = caseById(selected);
  if (!entry) return;
  const total = (entry.run.events || []).length;
  shown = Math.min(Math.max(value, 0), total);
  $('scrub').value = String(shown);
  renderEvents();
}

$('scrub').addEventListener('input', (e) => { pauseReplay(); setShown(Number(e.target.value)); });
$('stepFwdBtn').addEventListener('click', () => { pauseReplay(); setShown(shown + 1); });
$('stepBackBtn').addEventListener('click', () => { pauseReplay(); setShown(shown - 1); });
$('allBtn').addEventListener('click', () => {
  pauseReplay();
  const entry = caseById(selected);
  setShown(entry ? (entry.run.events || []).length : 0);
});

