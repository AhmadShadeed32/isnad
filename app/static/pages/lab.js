function renderComparison(){
  const holder = $('comparisonBody');
  holder.replaceChildren();
  const comparison = bundle.comparison;
  if (!comparison){
    const p = document.createElement('p');
    p.className = 'caption';
    p.textContent = 'No single-fact variant was recorded for this scenario. An absent '
      + 'comparison is reported as absent rather than filled in with a different change.';
    holder.appendChild(p);
    return;
  }
  const changed = document.createElement('p');
  changed.className = 'caption';
  changed.textContent = 'Changed: ' + comparison.changed_field + ' — '
    + (comparison.before_value === null ? 'absent' : comparison.before_value) + ' → '
    + (comparison.after_value === null ? 'absent' : comparison.after_value)
    + '. Policy digest unchanged at ' + comparison.policy_digest + '.';
  holder.appendChild(changed);

  const grid = document.createElement('div');
  grid.className = 'grid2';
  [['Original fixture', comparison.base_outcome, comparison.base_run_id],
   ['One fact changed', comparison.variant_outcome, comparison.variant_run_id]].forEach(([label, outcome, runId]) => {
    const panel = document.createElement('div');
    panel.className = 'panel';
    const caption = document.createElement('div');
    caption.className = 'counter';
    caption.textContent = label;
    panel.appendChild(caption);
    const decision = document.createElement('div');
    decision.className = 'decision ' + (outcome.decision || '');
    decision.textContent = outcome.decision;
    panel.appendChild(decision);
    [['chain grade', outcome.chain_grade], ['risk score', outcome.confidence],
     ['evidence steps', outcome.evidence_steps], ['run id', runId]].forEach(([k, v]) => {
      const kv = document.createElement('div');
      kv.className = 'kv';
      const key = document.createElement('span');
      key.className = 'k';
      key.textContent = k;
      const value = document.createElement('span');
      value.className = 'num';
      value.textContent = v === null || v === undefined ? '—' : String(v);
      kv.append(key, value);
      panel.appendChild(kv);
    });
    grid.appendChild(panel);
  });
  holder.appendChild(grid);

  const effect = document.createElement('p');
  effect.className = 'caption';
  effect.style.marginTop = '12px';
  effect.textContent = comparison.effect === 'no_observed_effect'
    ? 'Removing this fact had no observed effect on this run. That is a result, not a '
      + 'failed experiment — it says the decision did not rest on that one input.'
    : 'The decision path changed. This shows the policy is sensitive to that input. It '
      + 'is not a prediction that changing the fact prevents fraud or produces ALLOW, '
      + 'and it is not advice to a customer to answer differently.';
  holder.appendChild(effect);
}

// --- I3: the evidence comparison ---------------------------------------------

function renderEvidence(){
  const holder = $('evidenceBody');
  holder.replaceChildren();
  const report = bundle.evidence_report;
  if (!report){
    const p = document.createElement('p');
    p.className = 'caption';
    p.textContent = 'No evidence comparison was recorded in this bundle.';
    holder.appendChild(p);
    return;
  }

  const ie = report.independent_evaluation || {};
  const methodsHead = document.createElement('div');
  methodsHead.className = 'counter';
  methodsHead.textContent = 'Three methods on identical authored evidence — '
    + (ie.case_count === null || ie.case_count === undefined ? 'unknown' : ie.case_count)
    + ' cases, dataset ' + ie.dataset_digest;
  holder.appendChild(methodsHead);

  const methodRows = Object.entries(ie.methods || {}).map(([name, m]) => {
    const rate = m.automatic_decision_rate || {};
    const calls = m.calls || {};
    return [
      name,
      rate.count + ' / ' + rate.total,
      rate.percent + '%',
      calls.total,
      calls.min + '–' + calls.max,
      (m.authored_expectation_disagreements || []).length
    ];
  });
  holder.appendChild(table(
    ['method', 'decided automatically', 'rate', 'total calls', 'calls per case', 'disagreements with the authored expectation'],
    methodRows, '620px'));
  const hint = document.createElement('p');
  hint.className = 'scroll-hint';
  hint.textContent = 'Scroll the table sideways for every column.';
  holder.appendChild(hint);

  const fdb = report.false_decline_baseline;
  if (fdb){
    const head = document.createElement('div');
    head.className = 'counter';
    head.style.marginTop = '18px';
    head.textContent = 'Against two rule-based baselines on a generated population — '
      + fdb.innocent_denominator + ' cases that should not be declined, '
      + fdb.guilty_denominator + ' that should be';
    holder.appendChild(head);
    const names = ['isnad', 'single-signal', 'collapse-unknowns'];
    holder.appendChild(table(
      ['method', 'false declines', 'of', 'missed fraud', 'of'],
      names.map(name => [
        name,
        fdb.false_declines[name], fdb.innocent_denominator,
        fdb.missed_fraud[name], fdb.guilty_denominator
      ]), '460px'));
  }

  (report.limits || []).forEach(line => {
    const p = document.createElement('p');
    p.className = 'caption';
    p.style.margin = '10px 0 0';
    p.textContent = line;
    holder.appendChild(p);
  });
}

// Model runs are explicit and never overwrite the recorded bundle.
function updateModelStatus(message){
  text('outcomeBasis', modelViews.has(selected) ? 'Fresh simulated outcome' : 'Recorded outcome');
  $('runLabLlm').disabled = modelBusy || !selected;
  $('showRecorded').disabled = !modelViews.has(selected);
  $('labModelStatus').textContent = message || (modelViews.has(selected)
    ? 'Fresh Gemini-requested simulation · actual selections are labeled in the trace. Unsigned; network evidence is simulated.'
    : 'Recorded Greedy run. Running Gemini uses the configured key’s quota with simulated network evidence.');
}
$('runLabLlm').addEventListener('click', async () => {
  if (!selected || modelBusy) return;
  await window.IsnadKey.ready;
  const path = '/v1/lab/run/' + encodeURIComponent(selected);
  const headers = window.IsnadKey.headers(path);
  if (headers['X-Isnad-Planner'] !== 'llm') {
    updateModelStatus('Choose Gemini in the Planner selector above, then run this case. A site or personal key is required.'); return;
  }
  const caseId = selected;
  modelBusy = true; pauseReplay();
  updateModelStatus('Gemini is investigating this synthetic case… This spends model quota.');
  try {
    const token = document.querySelector('meta[name="isnad-demo-token"]').content;
    const response = await fetch(path, {method:'POST',headers:{...headers,Authorization:'Bearer '+token}});
    const data = await response.json();
    if (!response.ok) throw new Error(typeof data.detail === 'string' ? data.detail : 'Model run failed. Try again.');
    modelRuns.set(caseId, data.run); modelViews.add(caseId);
    if (selected === caseId) selectCase(caseId);
  } catch (error) { updateModelStatus(error.message || 'Model run failed. Try again.'); }
  finally { modelBusy = false; $('runLabLlm').disabled = !selected; }
});
$('showRecorded').addEventListener('click', () => {
  modelViews.delete(selected); selectCase(selected);
});

